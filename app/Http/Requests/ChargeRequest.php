<?php

namespace App\Http\Requests;

use App\Models\Ticket;
use Illuminate\Foundation\Http\FormRequest;

class ChargeRequest extends FormRequest
{
    /**
     * Determine if the user is authorized to make this request.
     *
     * @return bool
     */
    public function authorize()
    {
        return true;
    }

    /**
     * Get the validation rules that apply to the request.
     *
     * @return array
     */
    public function rules()
    {
        return [
            'ticket' => 'required|exists:tickets,id',
            'quantity' => 'required|integer',
            'fname' => 'nullable',
            'lname' => 'nullable',
            'email' => 'required|email',
            'phone_number' => 'nullable',
            'agrees_to_terms' => 'required|boolean',
            'donation_amount' => 'nullable',
            'payment_method' => 'nullable',
            'promo_code' => 'nullable',
            'code' => 'nullable'
        ];
    }
    public function lname()
    {
        return $this->lname;
    }

    public function fname()
    {
        return $this->fname;
    }

    public function email()
    {
        return $this->email;
    }

    public function messages()
    {
        $msg = parent::messages(); // TODO: Change the autogenerated stub
        $msg['fname.required'] = "The first name field is required.";
        $msg['lname.required'] = "The last name field is required.";

        return $msg;
    }
    public function phone_number()
    {
        return $this->phone_number;
    }

    public function ticket()
    {
        return Ticket::findOrFail($this->ticket);
    }

    public function quantity()
    {
        return intval($this->quantity);
    }
}
